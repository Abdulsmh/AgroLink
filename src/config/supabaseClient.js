import { createClient } from '@supabase/supabase-js';

// Retrieve backend credentials from Vite environment variables
const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

if (!supabaseUrl || !supabaseAnonKey) {
  throw new Error('AgriLink Connection Error: Environment keys missing. Check .env configuration.');
}

/**
 * Singleton Supabase client instance using standard Web Storage persistence
 */
export const supabase = createClient(supabaseUrl, supabaseAnonKey, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: true,
  },
});
